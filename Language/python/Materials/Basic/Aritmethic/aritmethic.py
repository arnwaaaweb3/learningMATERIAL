# --------------------------------------------------
# OPERATORS
# --------------------------------------------------
a=5
b=3

#1. Addition (+)
print(a + b)
if (a + b) == 8:
    print("Hey! This is Addition!")

# This is a plus sign (+), and you use it to add two numbers together.

#2. Subtraction (-)
print(a - b)
if (a - b) == 2:
    print("Hey! This is Subtraction!")
    
# This is a minus sign (-), and you use it to subtract two numbers.

#3. Multiplication (*)
print(a * b)
if (a * b) == 15:
    print("Hey! This is Multiplication!")
    
# This is a asterisk (*), and you use it to multiply two numbers.

#4. True Division (/)
print(a / b)
if (a / b) == 1:
    print("Hey! This is Division! Well? to be exactly, it's True Division!")
    
# This is a forward slash (/), and you use it to divide two numbers.
# This is called "True Division" because it gives you the exact result, even if it's a decimal.
# When you use one slash (/), you will always get a float data type, because it doesn't perform any rounding.

#5. Floor Division (//)
print(a // b)
if (a // b) == 1:
    print("Hey! This is Floor Division!")
    
# This is a double forward slash (//), and you use it to divide two numbers.
# This is called "Floor Division" because it gives you the floor result, which is the largest integer less than or equal to the result.
# When you use double slashes (//), you will always get an integer data type, because it rounds down the result to the nearest whole number.

#6. Modulo (%)
print(a % b)
if (a % b) == 2:
    print("Hey! This is Modulo!")

# This is a percent sign (%), and you use it to find the remainder of two numbers.
# Why 2? Because when you divide 5 by 3, the quotient is 1 with a remainder of 2. So the modulo operator gives you that remainder, which is 2 in this case.

#7. Exponentiation (**)
print(a ** b)
if (a ** b) == 125:
    print("Hey! This is Exponentiation!")

# This is a double asterisk (**), and you use it to raise one number to the power of another.
# Think of it as performing a multiplication operation a certain number of times.

